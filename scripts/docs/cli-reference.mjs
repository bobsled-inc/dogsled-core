#!/usr/bin/env node
// Writes docs/reference/cli.md from `bobsled --help`, walking every subcommand.
// Usage: node scripts/docs/cli-reference.mjs > docs/reference/cli.md
//        node scripts/docs/cli-reference.mjs --check   (fails when the committed page is stale)
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const check = process.argv.includes('--check');
const page = path.join(root, 'docs', 'reference', 'cli.md');
Object.assign(process.env, { NO_COLOR: '1', BOBSLED_CORE_OUTPUT_FORMAT: 'text' });

const programs = new Map();
for (const [name, entry] of [
  ['bobsled', 'bobsled-core/dist/index.js'],
  ['entity-graph', 'entity-graph/dist/cli.js'],
  ['model', 'model-spec/dist/index.js'],
  ['extract', 'extractor/dist/index.js'],
  ['load', 'loader/dist/index.js'],
  ['embed', 'embedder/dist/index.js'],
]) {
  const { buildProgram } = await import(pathToFileURL(path.join(root, 'packages', entry)).href);
  programs.set(name, pinHelpWidth(buildProgram()));
}

function pinHelpWidth(command) {
  command.configureHelp({ ...command.configureHelp(), helpWidth: 80 });
  command.configureOutput({ getOutHelpWidth: () => 80 });
  for (const child of command.commands) pinHelpWidth(child);
  return command;
}

export function delegatedCommand(args, command) {
  const [group, ...names] = args;
  let program = programs.get(group);
  if (group === 'activate') {
    program = programs.get('entity-graph');
    names.unshift('activate');
  }
  if (group === 'mcp') {
    program = programs.get('extract');
    names.unshift('mcp');
  }
  if (args.length < 2 || !program) return command;
  for (const name of names) {
    program = program.commands.find(
      (child) => child.name() === name || child.aliases().includes(name)
    );
    if (!program) return command;
  }
  return program;
}

const { runBobsledModelRunCommand } = await import(
  pathToFileURL(path.join(root, 'packages/bobsled-core/dist/commands/model-run.js')).href
);
let modelRunHelp = '';
const write = process.stdout.write;
try {
  process.stdout.write = (chunk) => {
    modelRunHelp += chunk;
    return true;
  };
  await runBobsledModelRunCommand(['--help']);
} finally {
  process.stdout.write = write;
}

function walk(args, shell) {
  const command = delegatedCommand(args, shell);
  const text = (
    args.join(' ') === 'model run' ? modelRunHelp : command.helpInformation()
  ).trimEnd();
  const title = ['bobsled', ...args].join(' ');
  const anchorDepth = Math.min(args.length + 2, 4);
  const children = command
    .createHelp()
    .visibleCommands(command)
    .filter((child) => child.name() !== 'help')
    .flatMap((child) => walk([...args, child.name()], child));
  return [`${'#'.repeat(anchorDepth)} \`${title}\`\n\n\`\`\`text\n${text}\n\`\`\``, ...children];
}

const sections = walk([], programs.get('bobsled'));
const output = [
  '# CLI reference',
  '',
  'Every `bobsled` command and flag, as printed by `--help`. Run `bobsled <command> --help`',
  'for the same text. This page is generated by `node scripts/docs/cli-reference.mjs`;',
  'regenerate it after changing a command.',
  '',
  ...sections.flatMap((section) => [section, '']),
].join('\n');

if (check) {
  if (readFileSync(page, 'utf8') !== output) {
    process.stderr.write(
      'docs/reference/cli.md is out of date. Build, then run: node scripts/docs/cli-reference.mjs > docs/reference/cli.md\n'
    );
    process.exit(1);
  }
  process.stdout.write('docs/reference/cli.md matches `bobsled --help`.\n');
} else {
  process.stdout.write(output);
}
