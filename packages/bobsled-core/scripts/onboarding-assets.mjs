import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../src/runtime/onboarding/', import.meta.url);
const read = (name) => readFile(new URL(`assets/${name}`, root), 'utf8');
const icons = JSON.parse(await read('icons.json'));
const mark = Buffer.from(await read('bobsled-mark.svg')).toString('base64');
const notices = `/* Embedded font licenses:\n${await read('Inter-OFL.txt')}\n${await read('Roboto-Mono-OFL.txt')}\n*/\n`;
const source = `// @generated by scripts/onboarding-assets.mjs. Edit assets/ and regenerate.\nexport const fontFaces = ${JSON.stringify(notices + (await read('fonts.css')))};\nexport const artifactStyle = ${JSON.stringify(await read('layout.css'))};\nexport const bobsledMark = ${JSON.stringify(`data:image/svg+xml;base64,${mark}`)};\nexport const iconPaths = ${JSON.stringify(icons, null, 2)} as const;\n`;
const target = new URL('assets.generated.ts', root);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== source) {
    throw new Error(
      'Onboarding assets drifted. Run node packages/bobsled-core/scripts/onboarding-assets.mjs.'
    );
  }
} else {
  await writeFile(target, source);
}
process.stdout.write(
  `Onboarding assets ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${fileURLToPath(target).split('/').at(-1)}\n`
);
