function SubNavLink({ child, pathname }: { child: NavSubItem; pathname: string }) {
  const activePrefixes = child.activePrefixes ?? [child.href];
  const isActive = child.exact
    ? pathname === child.href
    : activePrefixes.some((prefix) => pathname === prefix || pathname.startsWith(prefix + '/'));
  return (
    <Link
      href={child.href}
      className={`hidden shrink-0 rounded-md py-1.5 pl-9 pr-3 text-xs transition-colors md:block ${
        isActive
          ? 'bg-primary/10 text-primary'
          : 'text-muted-foreground hover:text-foreground hover:bg-secondary'
      }`}
    >
      {child.label}
    </Link>
  );
}

function NavSection({ label, title }: { label?: string; title?: string }) {
  return (
    <div className="hidden md:block">
      <div className="border-t border-border/40 my-1" />
      {label ? (
        <div
          className="text-[10px] font-medium uppercase tracking-wider text-muted-foreground/50 px-3 pt-3 pb-1"
          title={title}
        >
          {label}
        </div>
      ) : null}
    </div>
  );
}

export function Sidebar({ items = NAV_ITEMS }: SidebarProps = {}) {
  const pathname = usePathname();

  return (
    <aside className="sticky top-0 z-40 flex w-full flex-col border-b border-border bg-card md:h-screen md:w-56 md:border-b-0 md:border-r">
      <div className="border-b border-border p-4">
        <Link href="/" className="flex items-center gap-2">
          <span className="text-sm font-semibold tracking-tight">Bobsled Core Explorer</span>
        </Link>
      </div>

      <nav className="flex gap-1.5 overflow-x-auto p-2 md:flex-1 md:flex-col md:gap-0.5 md:overflow-y-auto">
        {items.map((item, index) => {
          const activePrefixes = (item as NavItem).activePrefixes ?? [item.href];
          const isActive = (item as NavItem).exact
            ? pathname === item.href
            : activePrefixes.some((prefix) =>
                prefix === '/'
                  ? pathname === '/'
                  : pathname === prefix || pathname.startsWith(prefix + '/')
              );

          const previousGroup = index > 0 ? items[index - 1]!.group : null;
          const showGroupHeader = item.group !== null && item.group !== previousGroup;

          return (
            <div key={item.href} className="contents md:block">
              {showGroupHeader ? (
                item.group === 'separator' ? (
                  <NavSection />
                ) : (
                  <NavSection
                    label={item.group ?? undefined}
                    title={(item as NavItem).groupTitle}
                  />
                )
              ) : null}
              <Link
                href={item.href}
                className={`shrink-0 rounded-md px-3 py-2 text-xs transition-colors md:flex md:items-center md:gap-2.5 ${
                  isActive
                    ? 'bg-primary/10 text-primary'
                    : 'text-muted-foreground hover:text-foreground hover:bg-secondary'
                }`}
              >
                <NavIcon icon={item.icon as NavItemIcon} />
                {item.label}
              </Link>
              {isActive && (item as NavItem).children
                ? (item as NavItem).children!.map((child) => (
                    <SubNavLink key={child.href} child={child} pathname={pathname} />
                  ))
                : null}
            </div>
          );
        })}
      </nav>

      <div className="mt-auto hidden border-t border-border p-3 md:block">
        <ThemeToggle />
        <div className="mt-2 text-[10px] text-muted-foreground">Bobsled Core Explorer v0.1</div>
      </div>
    </aside>
  );
}
