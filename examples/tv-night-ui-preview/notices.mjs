import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

export async function writeRuntimeNotices(metadata, base, destination) {
  const used = new Set(
    Object.values(metadata.outputs).flatMap((output) =>
      Object.entries(output.inputs)
        .filter(([, value]) => value.bytesInOutput > 0)
        .map(([name]) => name)
    )
  );
  const packages = new Map();
  for (const input of used) {
    let directory = dirname(resolve(base, input));
    while (directory !== dirname(directory)) {
      let info;
      try {
        info = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
      } catch (error) {
        if (error.code !== 'ENOENT') throw error;
      }
      if (info) {
        if (info.name && info.name !== '@dogsled/ui' && !packages.has(info.name)) {
          const names = (await readdir(directory))
            .filter((name) => /^(?:licen[cs]e|copying|notice)(?:\.|$)/i.test(name))
            .sort();
          const texts = await Promise.all(
            names.map((name) => readFile(join(directory, name), 'utf8'))
          );
          if (!texts.length && info.name === 'react-remove-scroll-bar') {
            texts.push(
              await readFile(join(dirname(destination), 'react-remove-scroll-bar.txt'), 'utf8')
            );
          }
          if (!texts.length) throw new Error(`Missing license notice for ${info.name}.`);
          packages.set(info.name, { version: info.version, license: info.license, texts });
        }
        break;
      }
      directory = dirname(directory);
    }
  }
  const sections = [...packages.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([name, info]) => `${name}@${info.version} (${info.license})\n\n${info.texts.join('\n\n')}`
    );
  await writeFile(
    destination,
    `Third-party notices for the embedded tutorial preview runtime.\nGenerated by notices.mjs from the bundled package licenses.\n\n${sections.join('\n\n' + '='.repeat(72) + '\n\n')}\n`
  );
  return [...packages.entries()]
    .map(([name, info]) => ({ name, version: info.version, license: info.license }))
    .sort((a, b) => a.name.localeCompare(b.name));
}
